"""scripts/expand_db.py — توسيع قاعدة البيانات بعناصر منظمة."""
import json
import os
import shutil
from datetime import datetime

DB_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "minichat_db.json")


def load_db():
    with open(DB_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def save_db(db):
    # نسخة احتياطية أولاً
    bak = DB_PATH + ".bak_" + datetime.now().strftime("%Y%m%d_%H%M%S")
    shutil.copy2(DB_PATH, bak)
    with open(DB_PATH, "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, indent=2)
    print("[EXPAND] تم الحفظ في %s" % DB_PATH)
    print("[EXPAND] نسخة احتياطية: %s" % os.path.basename(bak))


def make_item(q, a, tag):
    return {"q": q, "a": a, "tags": [tag]}


