def build_items():
    items = []
    # العناصر الكيميائية
    for name, sym, num in CHEM_ELEMENTS:
        items.append(make_item(
            "ما هو عنصر %s" % name,
            "عنصر %s (الرمز %s) هو العنصر رقم %d في الجدول الدوري." % (name, sym, num),
            "chemistry"))
        items.append(make_item(
            "ما رمز عنصر %s" % name,
            "رمز عنصر %s هو %s." % (name, sym),
            "chemistry"))
    # الكواكب
    for name, desc in PLANETS:
        items.append(make_item("ما هو %s" % name, "%s: %s" % (name, desc), "astronomy"))
        items.append(make_item("ما هي معلومات عن %s" % name, "%s: %s" % (name, desc), "astronomy"))
    # العواصم
    for country, capital in CAPITALS:
        items.append(make_item("ما هي عاصمة %s" % country,
                               "عاصمة %s هي %s." % (country, capital), "geography"))
    # لغات البرمجة
    for name, desc in PROG_LANGS:
        items.append(make_item("ما هي لغة %s" % name, "%s: %s" % (name, desc), "technology"))
        items.append(make_item("ما هي %s" % name, "%s: %s" % (name, desc), "technology"))
    # العملات
    for name, code, country in CURRENCIES:
        items.append(make_item("ما هي عملة %s" % country,
                               "عملة %s هي %s (%s)." % (country, name, code), "economy"))
        items.append(make_item("ما هي %s" % name,
                               "%s (%s) هي عملة %s." % (name, code, country), "economy"))
    return items


def main():
    db = load_db()
    faq = db.get("faq", [])
    existing = set()
    for item in faq:
        if isinstance(item, dict):
            existing.add(item.get("q", "").strip())
    new_items = build_items()
    added = 0
    skipped = 0
    for it in new_items:
        if it["q"].strip() in existing:
            skipped += 1
            continue
        faq.append(it)
        existing.add(it["q"].strip())
        added += 1
    db["faq"] = faq
    print("[EXPAND] عدد العناصر الجديدة: %d" % added)
    print("[EXPAND] تم تخطي (مكرر): %d" % skipped)
    print("[EXPAND] الإجمالي الآن: %d" % len(faq))
    save_db(db)


if __name__ == "__main__":
    main()
