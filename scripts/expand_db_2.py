def build_items():
    items = []
    for q, a in EVENTS:
        items.append(mi(q, a, "history"))
        items.append(mi("معلومات عن: " + q[4:], a, "history"))
    for q, a in PEOPLE:
        items.append(mi(q, a, "biography"))
    for q, a in GEO:
        items.append(mi(q, a, "geography"))
    for q, a in TECH:
        items.append(mi(q, a, "technology"))
    return items

def main():
    db = load_db()
    faq = db.get("faq", [])
    existing = set()
    for it in faq:
        if isinstance(it, dict):
            existing.add(it.get("q", "").strip())
    new = build_items()
    added = 0
    skipped = 0
    for it in new:
        if it["q"].strip() in existing:
            skipped += 1
            continue
        faq.append(it)
        existing.add(it["q"].strip())
        added += 1
    db["faq"] = faq
    print("[EXPAND2] جديد: %d | مكرر: %d | الإجمالي: %d" % (added, skipped, len(faq)))
    save_db(db)

if __name__ == "__main__":
    main()
