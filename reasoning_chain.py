# 3) محرك سلاسل الاستدلال
# ═══════════════════════════════════════════════════════════════
class ReasoningChain:
    def __init__(self):
        self.causal = CAUSAL_RULES
        self.sequences = SEQUENCE_RULES

    def _matches(self, keyword, text):
        """هل الكلمة موجودة في النص؟ (مطابقة بالجذور)"""
        from derivation_engine import RootExtractor
        t = normalize_arabic(text)
        k = normalize_arabic(keyword)
        # 1) مطابقة مباشرة (كلمة كاملة فقط)
        import re as _r0
        if _r0.search(r'(?<![\u0600-\u06FF])' + _r0.escape(k) + r'(?![\u0600-\u06FF])', t):
            return True
        # 2) مطابقة بالجذور
        k_root = RootExtractor.extract(k)
        if not k_root or len(k_root) < 2:
            return False
        import re as _r
        for tok in _r.findall(r"[\u0600-\u06FF]+", t):
            if len(tok) < 3:
                continue
            tok_root = RootExtractor.extract(tok)
            if tok_root == k_root:
                return True
        return False

    def causal_chain(self, text, max_depth=4):
        """
        يبني سلسلة سبب → نتيجة متعددة الخطوات.
        مثال: "شمس" → "حرارة" → "تبخر" → "مطر"
        """
        chain = []
        current = None

        # ابحث عن نقطة البداية
        for cause, effect, conf in self.causal:
            if self._matches(cause, text):
                current = effect
                chain.append((cause, effect, conf))
                break

        if not chain:
            return []

        # توسّع
        for _ in range(max_depth - 1):
            found = False
            for cause, effect, conf in self.causal:
                if canonical(cause) == canonical(current):
                    chain.append((cause, effect, conf))
                    current = effect
                    found = True
                    break
            if not found:
                break

        return chain

    def multi_hop(self, text):
        """استدلال متعدد الخطوات من المصفوفة."""
        t = normalize_arabic(text)
        for seq in self.sequences:
            if all(self._matches(k, t) for k in seq[:2]):
                return list(seq)
        return []

    def why_chain(self, text):
        """
        يجيب على "لماذا X؟"
        بالبحث عن X في قاعدة السبب-النتيجة.
        """
        for cause, effect, conf in self.causal:
            if self._matches(cause, text):
                return {
                    "cause": cause,
                    "effect": effect,
                    "confidence": conf,
                }
        return None

    def what_if(self, text):
        """
        يجيب على "ماذا لو X؟"
        """
        t = normalize_arabic(text)
        for cause, effect, conf in self.causal:
            if self._matches(cause, t):
                return "إذا %s → %s (احتمال %d%%)" % (cause, effect, int(conf * 100))
        return None

    def deduction(self, a, b, c):
        """
        استدلال منطقي: إذا A→B و B→C ⇒ A→C
        """
        # A→B؟
        ab = None
        bc = None
        for cause, effect, conf in self.causal:
            if canonical(cause) == canonical(a):
                ab = effect
            if canonical(cause) == canonical(b):
                bc = effect
        if ab and bc and canonical(ab) == canonical(b):
            return {
                "premise1": "%s → %s" % (a, b),
                "premise2": "%s → %s" % (b, c),
                "conclusion": "%s → %s" % (a, c),
            }
        return None

    def format_chain(self, chain):
        """شكل أنيق للسلسلة."""
        if not chain:
            return None
        lines = ["🔗 سلسلة الاستدلال:"]
        for cause, effect, conf in chain:
            lines.append("  • %s → %s (%d%%)" % (cause, effect, int(conf * 100)))
        return "\n".join(lines)


