# ============================================================
# نبرة عامة — للتوازن
# ============================================================
def get_opener(mood):
    """يعيد مقدمة عاطفية مناسبة."""
    if not mood or mood not in MOOD_OPENERS:
        return None
    return random.choice(MOOD_OPENERS[mood])


def get_closer(mood):
    """يعيد لمسة ختامية مناسبة."""
    if not mood or mood not in MOOD_CLOSERS:
        return None
    return random.choice(MOOD_CLOSERS[mood])


