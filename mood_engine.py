def detect_mood(text):
    """يكتشف المزاج من النص. يعيد: (المزاج، درجة الثقة، الكلمة المفتاح)"""
    if not text:
        return None, 0.0, None
    t = normalize_arabic(text)
    scores = {}
    hit_words = {}
    for mood, keywords in MOOD_KEYWORDS.items():
        score = 0
        hits = []
        for kw in keywords:
            nk = normalize_arabic(kw)
            if nk and nk in t:
                # الكلمات الأطول أعلى وزناً
                weight = 2 if len(nk) >= 5 else 1
                score += weight
                hits.append(kw)
        if score > 0:
            scores[mood] = score
            hit_words[mood] = hits
    if not scores:
        return None, 0.0, None
    best = max(scores.items(), key=lambda x: x[1])
    mood, score = best
    # درجة ثقة تقريبية
    confidence = min(0.95, score / 4.0)
    return mood, confidence, hit_words.get(mood, [])


